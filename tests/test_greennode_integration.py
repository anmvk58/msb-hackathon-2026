def test_greennode_llm_structured_output() -> None:
    client = GreenNodeLLMClient(
        base_url="https://maas.example.test/v1",
        model="enabled-model-path",
        api_key="vn-test-secret",
        transport=decision_transport(),
    )
    decision = client.generate_structured(
        system_prompt="system",
        user_prompt="choose",
        response_model=LLMRecommendationDecision,
        context={"candidate_plan": {"candidate_options": [{"option_id": "A"}]}},
    )
    assert decision.recommended_option_id == "A"


def test_llm_cannot_introduce_unknown_option(session: Session) -> None:
    plan = CandidateActionGenerator().generate(
        session,
        customer_id="C001",
        as_of=date(2026, 9, 1),
        primary_type=SignalType.CASHFLOW_RISK,
        analysis={
            "risk_level": "HIGH",
            "forecast_balance": "1366667",
            "safe_balance": "3000000",
            "gap": "-1633333",
            "confidence": "0.9110",
            "drivers": [],
        },
    )
    decision = LLMRecommendationDecision(
        summary="malicious",
        recommended_option_id="TRANSFER_MONEY",
        reasoning_summary="malicious",
    )
    with pytest.raises(ValueError, match="not generated by business logic"):
        assemble_recommendation(plan, decision)


