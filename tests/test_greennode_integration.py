def test_c001_real_agent_flow_with_mock_transport(session: Session) -> None:
    runtime = build_agent_runtime(
        settings=greennode_settings(), llm_transport=decision_transport()
    )
    state = runtime.run(
        session,
        customer_id="C001",
        message="Tài chính tháng này của tôi thế nào?",
        as_of=date(2026, 9, 1),
    )
    assert state.state == AgentLifecycle.RECOMMENDATION_READY
    assert state.recommendation.recommended_option_id == "A"
    assert state.recommendation.options[0].parameters["amount"] == "4000000"


def test_confirmation_still_required_with_greennode_runtime(
    session: Session,
) -> None:
    runtime = build_agent_runtime(
        settings=greennode_settings(), llm_transport=decision_transport()
    )
    waiting = runtime.run(
        session,
        customer_id="C001",
        message="Chọn A",
        as_of=date(2026, 9, 1),
        selected_option_id="A",
    )
    assert waiting.state == AgentLifecycle.WAITING_CONFIRMATION
    assert session.scalar(select(Budget).where(Budget.customer_id == "C001")) is None
    executed = runtime.confirm(
        session, action_id=waiting.action_id, confirmed=True
    )
    assert executed.state == AgentLifecycle.EXECUTED
    budget = session.scalar(select(Budget).where(Budget.customer_id == "C001"))
    assert budget is not None
    assert budget.amount == Decimal("4000000")


