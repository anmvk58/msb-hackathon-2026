def local_settings() -> Settings:
    return Settings(_env_file=None, agent_runtime="local")


def greennode_settings(**overrides) -> Settings:
    values = {
        "_env_file": None,
        "agent_runtime": "greennode",
        "llm_provider": "greennode",
        "llm_base_url": "https://maas.example.test/v1",
        "llm_model": "enabled-model-path",
        "llm_api_key": "vn-test-secret",
        "greennode_client_id": "iam-client",
        "greennode_client_secret": "iam-secret",
    }
    values.update(overrides)
    return Settings(**values)


def decision_transport(option_id: str = "A") -> httpx.MockTransport:
    def handler(request: httpx.Request) -> httpx.Response:
        assert request.url.path == "/v1/chat/completions"
        assert request.headers["authorization"] == "Bearer vn-test-secret"
        payload = json.loads(request.content)
        assert payload["model"] == "enabled-model-path"
        return httpx.Response(
            200,
            json={
                "choices": [
                    {
                        "message": {
                            "content": json.dumps(
                                {
                                    "summary": "Dòng tiền có nguy cơ xuống dưới mức an toàn.",
                                    "recommended_option_id": option_id,
                                    "reasoning_summary": "Ưu tiên kiểm soát shopping theo evidence.",
                                }
                            )
                        }
                    }
                ]
            },
        )

    return httpx.MockTransport(handler)


